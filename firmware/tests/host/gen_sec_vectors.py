#!/usr/bin/env python3
"""Generate sec_vectors.h: reference values for test_sec.c from an independent implementation.

Uses the Python "cryptography" package (X25519, HKDF-SHA256, HMAC-SHA256, AES-256-GCM).
    pip install cryptography
    python3 firmware/tests/host/gen_sec_vectors.py > firmware/tests/host/sec_vectors.h
"""
import hashlib
import hmac

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

PAD_BLOCK = 32
OVERHEAD = 5 + 16

PSK = bytes(range(0x20, 0x40))
NC = bytes(range(0xA0, 0xB0))
NP = bytes(range(0xC0, 0xD0))
# Raw 32-byte X25519 private keys (clamped inside both implementations).
ESK_C = bytes((0x41 + 7 * i) & 0xFF for i in range(32))
ESK_P = bytes((0x93 + 11 * i) & 0xFF for i in range(32))


def raw_pub(sk):
    return X25519PrivateKey.from_private_bytes(sk).public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw)


EPK_C = raw_pub(ESK_C)
EPK_P = raw_pub(ESK_P)
DH = X25519PrivateKey.from_private_bytes(ESK_C).exchange(X25519PublicKey.from_public_bytes(EPK_P))
assert DH == X25519PrivateKey.from_private_bytes(ESK_P).exchange(X25519PublicKey.from_public_bytes(EPK_C))

SALT = NC + NP + EPK_C + EPK_P
IKM = PSK + DH


def hkdf(label):
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=SALT, info=label).derive(IKM)


K_C2P = hkdf(b"keyrelay v2 c2p")
K_P2C = hkdf(b"keyrelay v2 p2c")
K_AUTH = hkdf(b"keyrelay v2 auth")


def auth_mac(role):
    return hmac.new(K_AUTH, b"YD-AUTH" + bytes([role]) + NC + NP, hashlib.sha256).digest()[:16]


def gatt_uuid(kind):
    return hmac.new(PSK, b"keyrelay v2 gatt uuid" + bytes([kind]), hashlib.sha256).digest()[:16]


GATT_SVC = gatt_uuid(0)
GATT_TO_DESK = gatt_uuid(1)
GATT_TO_RECV = gatt_uuid(2)

MAC_C = auth_mac(ord("C"))
MAC_P = auth_mac(ord("P"))

CTR = 0x01020304


def header(ctr):
    return bytes([0xE1]) + ctr.to_bytes(4, "big")


def iv(ctr):
    return bytes(8) + ctr.to_bytes(4, "big")


def seal_raw(key, ctr, padded):
    return header(ctr) + AESGCM(key).encrypt(iv(ctr), padded, header(ctr))


def pad(pt, block=PAD_BLOCK):
    need = len(pt) + 1
    total = (need + block - 1) // block * block
    return pt + b"\x80" + bytes(total - need)


PT = bytes([0x01]) + b"hello keyrelay"           # channel byte + payload, 15 bytes -> padded to 32
SEALED = seal_raw(K_C2P, CTR, pad(PT))
PT31 = bytes(range(31))                           # 31 + 0x80 = exactly one block
SEALED31 = seal_raw(K_C2P, CTR + 1, pad(PT31))
PT_ZEROS = bytes([0x03, 0x00, 0x00])              # payload ending in zero bytes must survive unpadding
SEALED_ZEROS = seal_raw(K_C2P, CTR + 2, pad(PT_ZEROS))
BAD_NOMARK = seal_raw(K_C2P, CTR + 3, bytes(32))  # authentic, but no 0x80 marker
BAD_WRONGMARK = seal_raw(K_C2P, CTR + 4, b"\x01abc" + b"\x81" + bytes(27))


def c_array(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"


print("/* Generated by gen_sec_vectors.py with Python 'cryptography' (X25519, HKDF-SHA256, HMAC-SHA256,")
print(" * AES-256-GCM) as an independent reference. Do not edit by hand. */")
for name in ["PSK", "NC", "NP", "ESK_C", "ESK_P", "EPK_C", "EPK_P", "DH", "K_C2P", "K_P2C", "K_AUTH",
             "MAC_C", "MAC_P", "GATT_SVC", "GATT_TO_DESK", "GATT_TO_RECV", "PT", "SEALED", "PT31", "SEALED31",
             "PT_ZEROS", "SEALED_ZEROS",
             "BAD_NOMARK", "BAD_WRONGMARK"]:
    print(c_array(name, globals()[name]))
print(f"#define CTR 0x{CTR:08x}u")
